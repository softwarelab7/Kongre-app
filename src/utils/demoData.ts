/**
 * Genera 4 semanas pobladas con asignaciones completas de prueba
 */
export function generateDemoWeeks(): WeekSchedule[] {
  const weeks: WeekSchedule[] = [];

  for (let i = 0; i < 4; i++) {
    const monday = getMondayOfOffsetWeek(i);
    const baseWeek = createEmptyWeek(monday, i);

    // Asignaciones rotativas de entre semana
    const midweekPresidents = ['pub-coord', 'pub-sec', 'pub-serv', 'pub-vym'];
    const midweekPrayers = ['pub-sm-lit', 'pub-sm-terr', 'pub-sm-audio', 'pub-sm-plat'];
    const tesorosSpeakers = ['pub-coord', 'pub-vym', 'pub-serv', 'pub-sec'];
    const perlasSpeakers = ['pub-sec', 'pub-sm-lit', 'pub-vym', 'pub-sm-terr'];
    const bibleReaders = ['pub-pub-4', 'pub-pub-5', 'pub-sm-plat', 'pub-pub-4'];
    const wtConductors = ['pub-coord', 'pub-serv', 'pub-coord', 'pub-vym'];
    const wtReaders = ['pub-sm-lit', 'pub-sm-audio', 'pub-sm-terr', 'pub-sm-plat'];
    const weekendPresidents = ['pub-sec', 'pub-vym', 'pub-serv', 'pub-coord'];

    const week: WeekSchedule = {
      ...baseWeek,
      midweek: {
        ...baseWeek.midweek,
        presidentId: midweekPresidents[i % midweekPresidents.length],
        initialPrayerId: midweekPrayers[i % midweekPrayers.length],
        finalPrayerId: midweekPresidents[(i + 1) % midweekPresidents.length],
        tesoros: {
          ...baseWeek.midweek.tesoros,
          discurso: {
            ...baseWeek.midweek.tesoros.discurso,
            publisherId: tesorosSpeakers[i % tesorosSpeakers.length],
            status: 'confirmada',
          },
          perlas: {
            ...baseWeek.midweek.tesoros.perlas,
            publisherId: perlasSpeakers[i % perlasSpeakers.length],
            status: 'confirmada',
          },
          lecturaBiblia: {
            ...baseWeek.midweek.tesoros.lecturaBiblia,
            publisherId: bibleReaders[i % bibleReaders.length],
            status: 'confirmada',
          },
        },
        maestros: {
          ...baseWeek.midweek.maestros,
          items: baseWeek.midweek.maestros.items.map((item, itemIdx) => {
            if (itemIdx === 0) {
              return {
                ...item,
                publisherId: 'pub-pion-1',
                assistantId: 'pub-pub-1',
                status: 'confirmada',
              };
            }
            if (itemIdx === 1) {
              return {
                ...item,
                publisherId: 'pub-pion-2',
                assistantId: 'pub-pub-2',
                status: 'confirmada',
              };
            }
            return {
              ...item,
              publisherId: 'pub-pub-3',
              assistantId: 'pub-pion-1',
              status: 'confirmada',
            };
          }),
        },
        vidaCristiana: {
          ...baseWeek.midweek.vidaCristiana,
          items: baseWeek.midweek.vidaCristiana.items.map((item) => ({
            ...item,
            publisherId: tesorosSpeakers[(i + 2) % tesorosSpeakers.length],
            status: 'confirmada',
          })),
          estudioBiblico: {
            conductorId: wtConductors[i % wtConductors.length],
            lectorId: wtReaders[i % wtReaders.length],
          },
        },
        duties: {
          deber_audio: ['pub-sm-audio'],
          deber_video: ['pub-sm-audio'],
          deber_microfonos: ['pub-sm-plat', 'pub-pub-4'],
          deber_plataforma: ['pub-sm-plat'],
          deber_acomodador: ['pub-sm-lit', 'pub-sm-terr'],
          deber_seguridad: ['pub-sm-terr'],
          deber_zoom: ['pub-vym'],
        },
      },
      weekend: {
        ...baseWeek.weekend,
        presidentId: weekendPresidents[i % weekendPresidents.length],
        publicTalkSpeaker: i % 2 === 0 ? 'Carlos Mendoza' : 'Hno. Roberto Peña (Orador Visitante - Cong. Norte)',
        publicTalkTheme: i % 2 === 0 ? '¿Por qué debemos amar a Dios sobre todas las cosas?' : 'El Reino de Dios: la única esperanza para la humanidad',
        publicTalkOutlineNumber: i % 2 === 0 ? 32 : 14,
        isVisitingSpeaker: i % 2 !== 0,
        visitingSpeakerCongregation: i % 2 !== 0 ? 'Congregación Norte' : undefined,
        visitingSpeakerPhone: i % 2 !== 0 ? '+52 55 9988 7766' : undefined,
        hospitalityPublisherId: 'pub-pion-1',
        atalayaConductorId: wtConductors[i % wtConductors.length],
        atalayaLectorId: wtReaders[i % wtReaders.length],
        initialPrayerId: midweekPrayers[(i + 1) % midweekPrayers.length],
        finalPrayerId: weekendPresidents[i % weekendPresidents.length],
        duties: {
          deber_audio: ['pub-sm-audio'],
          deber_video: ['pub-sm-audio'],
          deber_microfonos: ['pub-sm-plat', 'pub-pub-4'],
          deber_plataforma: ['pub-sm-plat'],
          deber_acomodador: ['pub-sm-lit', 'pub-sm-terr'],
          deber_seguridad: ['pub-sm-terr'],
          deber_zoom: ['pub-coord'],
        },
      },
    };

    weeks.push(week);
  }

  return weeks;
}

