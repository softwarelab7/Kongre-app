export function findOutlineByNumber(num: number): PublicTalkOutline | undefined {
  return OFFICIAL_PUBLIC_TALK_OUTLINES.find(o => o.number === num);
}

export function searchOutlines(query: string): PublicTalkOutline[] {
  const clean = query.toLowerCase().trim();
  const num = parseInt(clean, 10);
  if (!isNaN(num)) {
    return OFFICIAL_PUBLIC_TALK_OUTLINES.filter(o => o.number === num);
  }
  return OFFICIAL_PUBLIC_TALK_OUTLINES.filter(
    o => o.title.toLowerCase().includes(clean) || (o.category && o.category.toLowerCase().includes(clean))
  );
}
